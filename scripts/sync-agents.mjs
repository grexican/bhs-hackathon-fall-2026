#!/usr/bin/env node
// Keeps Claude Code and Cursor looking at the same instructions.
//
// Both tools already read .claude/skills/ (skills double as /slash commands) and
// .claude/agents/. Cursor cannot read .claude/rules/, so each rule is mirrored to
// .cursor/rules/<name>.mdc. Also writes .claude/skills/CATALOG.md so humans and agents
// can see every skill at a glance.
//
//   npm run agents:sync          write mirrors + catalog
//   npm run agents:check         fail if anything is stale or a skill is malformed
import fs from "node:fs";
import path from "node:path";
import { fileURLToPath } from "node:url";

const ROOT = path.resolve(path.dirname(fileURLToPath(import.meta.url)), "..");
const CHECK = process.argv.includes("--check");
const GENERATED = "<!-- GENERATED by scripts/sync-agents.mjs. Edit the canonical file, then run npm run agents:sync -->";
const problems = [];

function frontmatter(raw) {
  const m = raw.replace(/\r/g, "").match(/^---\n([\s\S]*?)\n---\n?([\s\S]*)$/);
  if (!m) return { meta: {}, body: raw };
  const meta = {};
  const lines = m[1].split("\n");
  for (let i = 0; i < lines.length; i++) {
    const kv = lines[i].match(/^([\w-]+):\s*(.*)$/);
    if (!kv) continue;
    let value = kv[2].trim();
    // Folded / literal blocks: gather the indented lines that follow.
    if (/^[>|][-+]?$/.test(value) || value === "") {
      const block = [];
      while (i + 1 < lines.length && /^\s+\S/.test(lines[i + 1])) block.push(lines[++i].trim());
      // A YAML list (`paths:` in a rule) becomes Cursor's comma-separated globs.
      value = block.length && block.every((l) => l.startsWith("- "))
        ? block.map((l) => l.slice(2).trim().replace(/^["']|["']$/g, "")).join(",")
        : block.join(" ");
    }
    meta[kv[1]] = value.replace(/^["']|["']$/g, "");
  }
  return { meta, body: m[2] };
}

function emit(rel, contents) {
  const abs = path.join(ROOT, rel);
  const current = fs.existsSync(abs) ? fs.readFileSync(abs, "utf8") : null;
  if (current === contents) return;
  if (CHECK) return problems.push(`stale: ${rel} (run npm run agents:sync)`);
  fs.mkdirSync(path.dirname(abs), { recursive: true });
  fs.writeFileSync(abs, contents);
  console.log(`  wrote ${rel}`);
}

function skills() {
  const dir = path.join(ROOT, ".claude", "skills");
  const rows = [];
  for (const name of fs.readdirSync(dir).sort()) {
    const file = path.join(dir, name, "SKILL.md");
    if (!fs.existsSync(file)) continue;
    const { meta } = frontmatter(fs.readFileSync(file, "utf8"));
    if (!meta.name) problems.push(`.claude/skills/${name}/SKILL.md: missing name`);
    else if (meta.name !== name) problems.push(`.claude/skills/${name}/SKILL.md: name "${meta.name}" does not match its folder`);
    if (!meta.description) problems.push(`.claude/skills/${name}/SKILL.md: missing description`);
    // routed-by: not auto-picked; a director skill reads it when the task needs it.
    rows.push({ name, description: meta.description ?? "", command: meta["disable-model-invocation"] === "true" && !meta["routed-by"], routedBy: meta["routed-by"] });
  }
  return rows;
}

function agents() {
  const dir = path.join(ROOT, ".claude", "agents");
  if (!fs.existsSync(dir)) return [];
  return fs
    .readdirSync(dir)
    .filter((f) => f.endsWith(".md"))
    .sort()
    .map((f) => {
      const { meta } = frontmatter(fs.readFileSync(path.join(dir, f), "utf8"));
      if (!meta.name || !meta.description) problems.push(`.claude/agents/${f}: needs name and description`);
      return { name: meta.name ?? f.replace(/\.md$/, ""), description: meta.description ?? "" };
    });
}

function rules() {
  const dir = path.join(ROOT, ".claude", "rules");
  const out = path.join(ROOT, ".cursor", "rules");
  const sources = fs.existsSync(dir) ? fs.readdirSync(dir).filter((f) => f.endsWith(".md")) : [];
  if (fs.existsSync(out)) {
    for (const f of fs.readdirSync(out)) {
      const abs = path.join(out, f);
      if (!f.endsWith(".mdc") || !fs.readFileSync(abs, "utf8").includes(GENERATED)) continue;
      if (sources.includes(f.replace(/\.mdc$/, ".md"))) continue;
      if (CHECK) problems.push(`orphan mirror: .cursor/rules/${f}`);
      else fs.unlinkSync(abs);
    }
  }
  for (const f of sources) {
    const { meta, body } = frontmatter(fs.readFileSync(path.join(dir, f), "utf8"));
    const globs = meta.paths ?? "";
    emit(
      `.cursor/rules/${f.replace(/\.md$/, ".mdc")}`,
      `---\ndescription: ${JSON.stringify(meta.description ?? f)}\nglobs: ${JSON.stringify(globs)}\nalwaysApply: ${globs ? "false" : "true"}\n---\n\n${GENERATED}\n\n${body.trim()}\n`,
    );
  }
}

const cell = (s) => s.replace(/\|/g, "\\|").replace(/\s+/g, " ").trim();
const skillRows = skills();
const agentRows = agents();
rules();
emit(
  ".claude/skills/CATALOG.md",
  `# Skills and agents\n\n${GENERATED}\n\nType \`/name\` in Cursor or Claude Code to run a workflow. Other skills load on their own when the task matches their description.\n\n## Workflows (slash commands)\n\n| Command | What it does |\n|---|---|\n${skillRows
    .filter((r) => r.command)
    .map((r) => `| \`/${r.name}\` | ${cell(r.description)} |`)
    .join("\n")}\n\n## Skills (${skillRows.filter((r) => !r.command && !r.routedBy).length})\n\n| Skill | Use it when |\n|---|---|\n${skillRows
    .filter((r) => !r.command && !r.routedBy)
    .map((r) => `| \`${r.name}\` | ${cell(r.description)} |`)
    .join("\n")}\n\n## Routed skills (${skillRows.filter((r) => r.routedBy).length})\n\nNot picked automatically: a director skill reads them (\`.claude/skills/<name>/SKILL.md\`) when the task needs them. Each still runs as \`/name\`.\n\n| Skill | Routed by | What it covers |\n|---|---|---|\n${skillRows
    .filter((r) => r.routedBy)
    .map((r) => `| \`${r.name}\` | \`${r.routedBy}\` | ${cell(r.description)} |`)
    .join("\n")}\n\n## Subagents\n\n| Agent | Role |\n|---|---|\n${agentRows.map((r) => `| \`${r.name}\` | ${cell(r.description)} |`).join("\n")}\n`,
);

if (problems.length) {
  for (const p of problems) console.error(`✗ ${p}`);
  process.exit(1);
}
console.log(CHECK ? "agents: in sync" : "agents: synced");
